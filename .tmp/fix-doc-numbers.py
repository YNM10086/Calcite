def apply(path, old, new, expect):
    with io.open(path, encoding="utf-8") as fh:
        text = fh.read()
    n = text.count(old)
    if n != expect:
        print(f"  [XX] {path} 期望命中 {expect} 次，实际 {n} 次：{old[:60]}")
        return False
    with io.open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text.replace(old, new))
    print(f"  [OK] {path.split('/')[-1]}  {old[:52]}…")
    return True


def main():
    ok = True
    for path, old, new, expect in EDITS:
        ok = apply(path, old, new, expect) and ok
    print()
    print("全部替换成功" if ok else "有替换失败，见上面的 [XX]")
    if not ok:
        sys.exit(1)


main()
